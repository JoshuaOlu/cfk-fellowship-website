def main():
    parser = argparse.ArgumentParser(description='Set up a new cohort.')
    parser.add_argument('--name',    required=True, help='Full cohort name (e.g. "Spring 2027")')
    parser.add_argument('--season',  required=True, choices=['spring', 'autumn'],
                        help='Season: spring or autumn')
    parser.add_argument('--year',    required=True, help='Year (e.g. 2027)')
    parser.add_argument('--fellows', required=True, help='CSV of new Foundation Fellows')
    parser.add_argument('--dry-run', action='store_true',
                        help='Preview without writing any files.')
    args = parser.parse_args()

    cohort_slug = make_cohort_slug(args.season, args.year)

    csv_path = args.fellows if os.path.isabs(args.fellows) else os.path.join(REPO_ROOT, args.fellows)
    if not os.path.exists(csv_path):
        print(f"ERROR: Fellows CSV not found: {csv_path}")
        sys.exit(1)

    with open(csv_path, 'r', encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        normalise_headers(reader)
        headers = reader.fieldnames or []
        for col in ['first_name', 'last_name', 'track']:
            if col not in headers:
                print(f"ERROR: CSV missing required column: '{col}'")
                sys.exit(1)
        fellows = [
            {'first_name': clean_text(r['first_name']).strip(),
             'last_name':  r['last_name'].strip(),
             'track':      r['track'].strip(),
             'photo':      r.get('photo', '').strip()}
            for r in reader
            if r.get('first_name', '').strip()
        ]

    if not fellows:
        print("ERROR: No Fellows found in CSV.")
        sys.exit(1)

    print(f"\nSetting up new cohort: {args.name}")
    print(f"Slug: {cohort_slug}  |  Fellows: {len(fellows)}")
    if args.dry_run:
        print("DRY RUN — no files will be written.\n")
    print()

    create_fellows_list(fellows, cohort_slug, args.dry_run)
    create_cohort_page(cohort_slug, args.name, args.dry_run)
    update_cohorts_yml(cohort_slug, args.name, args.season, args.year, len(fellows), args.dry_run)
    update_current_cohort_yml(cohort_slug, args.name, args.season, args.year, len(fellows), args.dry_run)
    update_site_status(args.dry_run)

    print(f"\n{'─'*55}")
    print(f"✅ Cohort setup {'preview' if args.dry_run else 'complete'}!")
    if not args.dry_run:
        print(f"\n⚠️  STILL TO DO (manually):")
        print(f"  → Add the registration form URL to _data/current_cohort.yml (apply_url)")
        print(f"  → Add the waitlist URL to _data/current_cohort.yml (waitlist_url)")
        print(f"  → Update the cohort description in _data/cohorts.yml")
        print(f"  → Update the announcement messages in _data/current_cohort.yml if needed")
        print(f"  → Upload headshots to assets/images/cohorts/{cohort_slug}/")
        print(f"  → Commit and push to GitHub")
        print(f"\n  Site status is now: recruiting")
        print(f"  Cohort page will be at: /cohorts/{cohort_slug}/")


if __name__ == '__main__':
    main()
