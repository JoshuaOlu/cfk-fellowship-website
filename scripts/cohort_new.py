def update_cohorts_yml(cohort_slug, cohort_name, season, year, fellow_count, dry_run=False):
    """Add the new cohort to the top of _data/cohorts.yml"""
    path = os.path.join(DATA_DIR, 'cohorts.yml')
    with open(path, 'r', encoding='utf-8') as f:
        existing = f.read()

    start_month = 'February' if season.lower() == 'spring' else 'August'
    end_month   = 'May' if season.lower() == 'spring' else 'November'

    new_entry = f"""- name: "{cohort_name}"
  slug: "{cohort_slug}"
  season: "{season.title()}"
  year: "{year}"
  date_range: "{start_month} – {end_month} {year}"
  fellow_count: {fellow_count}
  status: "active"
  founding: false
  description: "The {cohort_name} cohort."
  report_url: ""

"""
    # Insert after the header comments, before the first entry
    if existing.strip().startswith('#'):
        # Find first '- name:' line
        idx = existing.find('- name:')
        if idx >= 0:
            updated = existing[:idx] + new_entry + existing[idx:]
        else:
            updated = existing + '\n' + new_entry
    else:
        updated = new_entry + existing

    if dry_run:
        print(f"  (DRY RUN) Would update: _data/cohorts.yml")
    else:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(updated)
        print(f"  ✅ _data/cohorts.yml (new entry added at top)")


