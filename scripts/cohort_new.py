def clean_text(value):
    """
    Fix common encoding garbling from Google Sheets CSV exports.
    Google Sheets exports UTF-8 without BOM; if read with wrong encoding,
    special characters appear garbled. This fixes the most common cases.
    """
    if not value:
        return value
    # Try to fix UTF-8 bytes misread as latin-1/cp1252
    try:
        fixed = value.encode('latin-1').decode('utf-8')
        return fixed
    except (UnicodeEncodeError, UnicodeDecodeError):
        pass
    # Manual fallback for the most common garbled sequences
    replacements = {
        'â€"': '—',   # em dash
        'â€™': "'",   # right single quote
        'â€˜': "'",   # left single quote
        'â€œ': '"',   # left double quote
        'â€':  '"',   # right double quote
        'â€¦': '…',   # ellipsis
        'Ã©':  'é',
        'Ã¨':  'è',
        'Ã ':  'à',
        'Ã¢':  'â',
        'Ã®':  'î',
        'Ã´':  'ô',
        'Ã»':  'û',
        'Ã§':  'ç',
        'Ã«':  'ë',
        'Ã¯':  'ï',
        'Ã¼':  'ü',
        'Ã¶':  'ö',
        'Ã¤':  'ä',
        'Ã±':  'ñ',
    }
    for garbled, correct in replacements.items():
        value = value.replace(garbled, correct)
    return value

def clean_row(row):
    """Apply clean_text to every value in a CSV row dict."""
    return {k: clean_text(v) if isinstance(v, str) else v for k, v in row.items()}

def normalise_headers(reader):
    """
    Strip asterisks and extra whitespace from CSV column headers.
    This allows headers like 'slug *' or 'first_name *' (used in the
    Google Sheets template as visual hints) to be read as 'slug', 'first_name'.
    """
    reader.fieldnames = [
        f.replace('*', '').strip()
        for f in (reader.fieldnames or [])
    ]
    return reader



from fellow_add import make_slug


def make_cohort_slug(season, year):
    return f"{season.lower()}-{year}"


def write_file(path, content, dry_run=False):
    """Write a file, or print it in dry-run mode."""
    if dry_run:
        print(f"  (DRY RUN) Would write: {os.path.relpath(path, REPO_ROOT)}")
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"  ✅ {os.path.relpath(path, REPO_ROOT)}")


def create_fellows_list(fellows, cohort_slug, dry_run=False):
    """Create _data/[cohort-slug]-fellows.yml"""
    lines = [
        f'# {cohort_slug}-fellows.yml',
        f'# Foundation Fellows for the {cohort_slug} cohort.',
        f'# Generated by cohort_new.py — edit as needed.',
        f'# When the cohort ends, run cohort_graduate.py to create permanent Fellow pages.',
        '',
    ]
    for f in fellows:
        slug = make_slug(f['first_name'], f['last_name'])
        photo = f.get('photo', '').strip() or f"/assets/images/cohorts/{cohort_slug}/{slug}.jpg"
        lines.append(f'- first_name: "{f["first_name"]}"')
        lines.append(f'  last_name: "{f["last_name"]}"')
        lines.append(f'  track: "{f["track"]}"')
        lines.append(f'  photo: "{photo}"')
        lines.append('')

    path = os.path.join(DATA_DIR, f'{cohort_slug}-fellows.yml')
    write_file(path, '\n'.join(lines), dry_run)
    return path


